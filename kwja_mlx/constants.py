def get_reading2reading_id() -> dict[str, int]:
    """Build reading -> id map: [UNK]=0, [ID]=1, then vocab.txt entries in file order."""
    reading2reading_id = {UNK: UNK_ID, ID: ID_ID}
    with open(READING_VOCAB_PATH, encoding="utf-8") as f:
        for line in f:
            if (line := line.strip()) and line not in reading2reading_id:
                reading2reading_id[line] = len(reading2reading_id)
    return reading2reading_id
